CREATE OR REPLACE VIEW easy_loans_view AS
SELECT DISTINCT
O.ORDER_ID,
O.CREATED_AT,
O.STATUS,
O.AMOUNT,
O.COUNTRY,
M.MERCHANT_ID,
M.NAME,
COUNT(R.AMOUNT) OVER(PARTITION BY O.ORDER_ID) AS REFUNDS_PER_ORDER,
COALESCE(SUM(R.AMOUNT) OVER(PARTITION BY O.ORDER_ID),0) AS TOTAL_REFUNDS
FROM 
ORDERS AS O 
LEFT JOIN 
MERCHANTS AS M ON O.MERCHANT_ID = M.MERCHANT_ID
LEFT JOIN 
REFUNDS AS R ON O.ORDER_ID = R.ORDER_ID;

SELECT * FROM easy_loans_view;